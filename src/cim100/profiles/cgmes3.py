"""CGMES 3.0 (IEC 61970-600-2) profiles, and a facade over exactly the classes they use.

Profiles: ``EQ SSH TP SV DL GL OP SC EQBD DY`` (`Profile` objects), `profiles`, `by_keyword`,
`by_uri`, `profiles_of`, `defining_profiles`, `classes` / `class_names` (union), `profile_set`.
Every class, enumeration and compound of those profiles is available by name, the same object as
``cim100.<Name>``::

    from cim100.profiles.cgmes3 import ACLineSegment, EQ, UnitSymbol

Classes outside CGMES 3.0 (market, work, asset, ...) are not listed here. Everything is lazy
(PEP 562): the snapshot is read and the model imported on first use. ``cgmes3.pyi`` (generated by
tools/gen_profile_stubs.py) gives type checkers and IDEs the names.
"""

from __future__ import annotations

from functools import cache
from importlib import import_module
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from typing import Any

    from cim100.profiles._model import ProfileSet

_API = (
    "by_keyword",
    "by_uri",
    "class_names",
    "classes",
    "defining_profiles",
    "profile_set",
    "profiles",
    "profiles_of",
)


@cache
def _set() -> ProfileSet:
    from cim100.profiles._model import ProfileSet

    return ProfileSet.load("cgmes_3_0.json", "CGMES 3.0")


def _public() -> list[str]:
    s = _set()
    return sorted({*s.keywords, *s.class_names, *_API})


def __getattr__(name: str) -> Any:
    if name == "__all__":
        return _public()
    if name.startswith("_"):
        raise AttributeError(f"module {__name__!r} has no attribute {name!r}")
    s = _set()
    if name == "profile_set":
        return s
    if name in _API:
        return getattr(s, name)
    if name in s:  # a profile keyword
        return s[name]
    if name in s.class_names:
        value = getattr(import_module("cim100"), name)
        globals()[name] = value
        return value
    raise AttributeError(f"module {__name__!r} has no attribute {name!r}")


def __dir__() -> list[str]:
    return sorted({*globals(), *_public()})
