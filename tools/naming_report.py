"""Write codegen/snapshot/naming_report.md from the committed IR snapshot.

Usage: naming_report.py [--out PATH] [--check]
  --check  do not write; exit 1 if the report on disk differs.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from codegen.normalize import load_snapshot, normalize

OUT = ROOT / "codegen" / "snapshot" / "naming_report.md"


def render() -> str:
    r = normalize(load_snapshot())
    rep = r.report
    L: list[str] = ["# CIM100 naming report", "", "Generated by `tools/naming_report.py`. Do not edit.", ""]

    L += ["## Counts", "", "| Item | Count |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in rep.counts]

    L += ["", "## Duplicate class names", "",
          "Canonical = most referenced; ties prefer non-Inf/non-Doc package, then lowest GUID.", "",
          "| CIM name | GUID | Package | py_name | Module | Canonical |", "|---|---|---|---|---|---|"]
    for n, g, pkg, py, mod, canon in rep.duplicate_classes:
        L.append(f"| {n} | `{g}` | {pkg} | {py} | `{mod}` | {'yes' if canon else 'no'} |")

    L += ["", "## Class names changed to be valid identifiers", ""]
    L += [f"- `{n}` -> `{py}` (`{g}`)" for g, n, py in rep.class_sanitized] or ["(none)"]

    L += ["", "## Renamed members", "",
          "| Class | Kind | CIM name | py_name | Reason |", "|---|---|---|---|---|"]
    for cn, _g, kind, cim, py, why in rep.member_renames:
        L.append(f"| {cn} | {kind} | {cim} | `{py}` | {why} |")

    L += ["", f"## Generated role names ({len(rep.generated_roles)} ends)", "",
          "Associations with no role name; role = snake(target class), plus `s` when many.", "",
          "| Owner class | Association GUID | py_name |", "|---|---|---|"]
    for cn, _g, ag, py in rep.generated_roles:
        L.append(f"| {cn} | `{ag}` | `{py}` |")

    L += ["", "## Sanitized enumeration literals (per enum)", "",
          "| Enum | Count | Examples (CIM -> py) |", "|---|---|---|"]
    for en, _g, rows in rep.sanitized_literals:
        ex = ", ".join(f"`{c}` -> `{p}`" for c, p in rows[:4])
        L.append(f"| {en} | {len(rows)} | {ex.replace('|', '/')} |")

    L += ["", "## Primitive fallbacks (mapped to `str`)", ""]
    L += [f"- {n} (`{g}`)" for n, g in rep.primitive_fallbacks] or ["(none)"]

    L += ["", "## Attribute defaults not converted (default = None)", ""]
    L += [f"- {c}.{a} = `{d}`" for c, a, d in rep.default_unparsed] or ["(none)"]
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", type=Path, default=OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    if a.check:
        return 0 if a.out.read_text(encoding="utf-8") == text else 1
    a.out.write_text(text, encoding="utf-8")
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
