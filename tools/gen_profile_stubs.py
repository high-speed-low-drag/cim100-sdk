"""Write src/cim100/profiles/cgmes3.pyi: names of the CGMES 3.0 facade for type checkers.

Usage: gen_profile_stubs.py [--check]
  --check  do not write; exit 1 if the file on disk differs from a fresh generation.

The stub imports every class and enumeration of the CGMES 3.0 profiles from its model module
(the same objects as ``cim100.<Name>``) and declares the profile objects and helpers.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

OUT = ROOT / "src" / "cim100" / "profiles" / "cgmes3.pyi"

HEADER = '''\
"""Generated by tools/gen_profile_stubs.py from the CGMES 3.0 snapshot. Do not edit."""

from cim100.profiles import _model
'''

FOOTER = """
profile_set: _model.ProfileSet
profiles: tuple[_model.Profile, ...]
classes: tuple[type, ...]
class_names: tuple[str, ...]

def by_keyword(keyword: str) -> _model.Profile: ...
def by_uri(uri: str) -> _model.Profile: ...
def profiles_of(cls: type | str, prop: str | None = None) -> tuple[_model.Profile, ...]: ...
def defining_profiles(cls: type | str) -> tuple[_model.Profile, ...]: ...
"""


def generate() -> str:
    from cim100 import _registry
    from cim100.profiles import cgmes3

    s = cgmes3.profile_set
    lines = [HEADER]
    for name in s.class_names:
        module, _, cls = _registry.BY_NAME[name].partition(":")
        lines.append(f"from {module} import {cls} as {name}")
    lines.append("")
    lines += [f"{kw}: _model.Profile" for kw in s.keywords]
    lines.append(FOOTER.rstrip("\n"))
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    text = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text("utf-8") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date; run tools/gen_profile_stubs.py")
            return 1
        print(f"{OUT.relative_to(ROOT)} is up to date")
        return 0
    OUT.write_text(text, "utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
